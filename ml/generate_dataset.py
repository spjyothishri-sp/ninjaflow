
"""
NinjaFlow - Synthetic Supply-Chain Transaction Dataset Generator

IMPORTANT:
All data generated by this script is COMPLETELY SYNTHETIC.
It does not contain real Ninjacart/customer/bank data.

Purpose:
Generate realistic-looking supply-chain transaction data for
training and demonstrating the NinjaFlow payment-delay ML model.
"""

import os
import numpy as np
import pandas as pd

# Reproducibility
np.random.seed(42)

# ---------------------------------------------------------
# CONFIGURATION
# ---------------------------------------------------------

NUM_ENTITIES = 40
NUM_TRANSACTIONS = 3000

REGIONS = [
    "Tamil Nadu",
    "Karnataka",
    "Kerala",
    "Andhra Pradesh",
    "Telangana",
    "Maharashtra",
    "Delhi",
    "Gujarat"
]

ENTITY_TYPES = ["SUPPLIER", "BUYER"]

# ---------------------------------------------------------
# CREATE ENTITY INFORMATION
# ---------------------------------------------------------

entities = []

for entity_id in range(1, NUM_ENTITIES + 1):

    entity_type = np.random.choice(ENTITY_TYPES)

    entities.append({
        "entity_id": entity_id,
        "entity_type": entity_type,
        "entity_name": f"{entity_type.title()}_{entity_id:02d}",
        "region": np.random.choice(REGIONS),

        # Different businesses have different payment behavior
        "base_delay": max(
            0,
            np.random.normal(loc=4.5, scale=3.0)
        ),

        # Current available cash
        "current_cash": np.random.uniform(
            50000,
            500000
        )
    })

entities_df = pd.DataFrame(entities)

# ---------------------------------------------------------
# GENERATE TRANSACTIONS
# ---------------------------------------------------------

transactions = []

start_date = pd.Timestamp("2026-01-01")

for i in range(NUM_TRANSACTIONS):

    entity = entities_df.sample(1).iloc[0]

    entity_id = int(entity["entity_id"])
    entity_type = entity["entity_type"]

    # Transaction date
    transaction_date = (
        start_date +
        pd.Timedelta(
            days=int(np.random.randint(0, 180))
        )
    )

    # Order amount
    order_amount = round(
        np.random.lognormal(
            mean=np.log(30000),
            sigma=0.65
        ),
        2
    )

    # Invoice is usually close to order amount
    invoice_amount = round(
        order_amount * np.random.uniform(0.97, 1.03),
        2
    )

    # Credit terms
    credit_days = int(
        np.random.choice(
            [7, 15, 30],
            p=[0.45, 0.35, 0.20]
        )
    )

    payment_due_date = (
        transaction_date +
        pd.Timedelta(days=credit_days)
    )

    # -----------------------------------------------------
    # SEASONALITY
    # -----------------------------------------------------

    month = transaction_date.month

    # Higher activity during selected months
    if month in [4, 5, 6, 10, 11]:
        season_index = np.random.uniform(0.70, 1.00)
    else:
        season_index = np.random.uniform(0.30, 0.70)

    # -----------------------------------------------------
    # HISTORICAL PAYMENT BEHAVIOR
    # -----------------------------------------------------

    historical_average_delay = max(
        0,
        entity["base_delay"] +
        np.random.normal(0, 1.5)
    )

    # -----------------------------------------------------
    # TRANSACTION FREQUENCY
    # -----------------------------------------------------

    order_frequency_per_month = round(
        np.random.uniform(2, 20),
        2
    )

    # -----------------------------------------------------
    # CURRENT CASH
    # -----------------------------------------------------

    current_cash = round(
        entity["current_cash"] *
        np.random.uniform(0.8, 1.2),
        2
    )

    # -----------------------------------------------------
    # OUTSTANDING RECEIVABLES
    # -----------------------------------------------------

    outstanding_receivables = round(
        np.random.uniform(
            10000,
            max(20000, order_amount * 8)
        ),
        2
    )

    # -----------------------------------------------------
    # UPCOMING PAYABLES
    # -----------------------------------------------------

    upcoming_payables = round(
        np.random.uniform(
            10000,
            max(20000, order_amount * 6)
        ),
        2
    )

    # -----------------------------------------------------
    # PAYMENT DELAY
    # -----------------------------------------------------

    # Base delay influenced by:
    # - historical behavior
    # - seasonality
    # - cash pressure
    # - randomness

    cash_pressure = max(
        0,
        (upcoming_payables - current_cash)
        / max(current_cash, 1)
    )

    delay_signal = (
        0.60 * historical_average_delay
        + 3.0 * season_index
        + 5.0 * cash_pressure
    )

    random_factor = np.random.normal(0, 3)

    payment_delay_days = int(
        round(
            max(
                -2,
                delay_signal + random_factor
            )
        )
    )

    # -----------------------------------------------------
    # CONTROL DELAY DISTRIBUTION
    # -----------------------------------------------------

    random_probability = np.random.random()

    if random_probability < 0.70:

        # 70% mostly on-time payments
        payment_delay_days = int(
            np.random.randint(-2, 2)
        )

    elif random_probability < 0.90:

        # 20% moderate delays
        payment_delay_days = int(
            np.random.randint(1, 11)
        )

    else:

        # 10% serious delays
        payment_delay_days = int(
            np.random.randint(10, 31)
        )

    # Add historical behavior influence
    if historical_average_delay > 8:
        payment_delay_days += int(
            np.random.randint(0, 5)
        )

    payment_delay_days = max(
        -2,
        min(payment_delay_days, 35)
    )

    # -----------------------------------------------------
    # PAID / PENDING TRANSACTION
    # -----------------------------------------------------

    # Most historical transactions are already paid.
    is_paid = np.random.random() < 0.85

    if is_paid:

        actual_payment_date = (
            payment_due_date +
            pd.Timedelta(
                days=payment_delay_days
            )
        )

        status = (
            "PAID"
            if payment_delay_days <= 0
            else "OVERDUE"
        )

    else:

        actual_payment_date = pd.NaT

        # For unpaid transactions, determine status
        if (
            payment_due_date
            < pd.Timestamp("2026-07-01")
        ):
            status = "OVERDUE"
        else:
            status = "PENDING"

    # -----------------------------------------------------
    # STORE ROW
    # -----------------------------------------------------

    transactions.append({

        "entity_id": entity_id,

        "entity_type": entity_type,

        "transaction_date":
            transaction_date.strftime("%Y-%m-%d"),

        "order_amount":
            round(order_amount, 2),

        "invoice_amount":
            round(invoice_amount, 2),

        "payment_due_date":
            payment_due_date.strftime("%Y-%m-%d"),

        "actual_payment_date":
            (
                actual_payment_date.strftime("%Y-%m-%d")
                if pd.notna(actual_payment_date)
                else None
            ),

        "payment_delay_days":
            payment_delay_days,

        "historical_average_delay":
            round(historical_average_delay, 2),

        "current_cash":
            round(current_cash, 2),

        "outstanding_receivables":
            round(outstanding_receivables, 2),

        "upcoming_payables":
            round(upcoming_payables, 2),

        "order_frequency_per_month":
            order_frequency_per_month,

        "region":
            entity["region"],

        "season_index":
            round(season_index, 3),

        # Target used by the ML model
        "label_delay_days":
            payment_delay_days
    })


# ---------------------------------------------------------
# CREATE DATAFRAME
# ---------------------------------------------------------

df = pd.DataFrame(transactions)

# ---------------------------------------------------------
# SAVE CSV
# ---------------------------------------------------------

# Go from ml/ back to project root, then into data/
project_root = os.path.dirname(
    os.path.dirname(
        os.path.abspath(__file__)
    )
)

data_directory = os.path.join(
    project_root,
    "data"
)

os.makedirs(
    data_directory,
    exist_ok=True
)

output_file = os.path.join(
    data_directory,
    "transactions.csv"
)

df.to_csv(
    output_file,
    index=False
)

# ---------------------------------------------------------
# SUMMARY
# ---------------------------------------------------------

print("=" * 60)
print("NinjaFlow Synthetic Dataset Generator")
print("=" * 60)

print(f"Generated transactions : {len(df)}")
print(
    f"Unique entities        : "
    f"{df['entity_id'].nunique()}"
)

print("\nDelay distribution:")

print(
    df["payment_delay_days"]
    .describe()
)

print("\nStatus distribution:")

print(
    df["payment_delay_days"]
    .apply(
        lambda x:
        "ON_TIME" if x <= 0
        else "MODERATE_DELAY" if x <= 10
        else "HIGH_DELAY"
    )
    .value_counts()
)

print("\nSaved to:")
print(output_file)

print("\nIMPORTANT:")
print("This dataset is 100% SYNTHETIC.")
print("It does not contain real company or customer data.")

print("=" * 60)
